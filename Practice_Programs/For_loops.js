// For Loop

// 1️⃣ Print "Hello" 5 times

for (let i = 0; i < 5; i++) {
    console.log("Hello");
}

// 2️⃣  Print numbers from 1 to 10
for (let j = 1; j <= 10; j++) {
    console.log(j);
}

// 3️⃣ Print even numbers from 1 to 20

for (let k = 1; k <= 20; k++) {
    if (k % 2 === 0)
        console.log(k);
}

// 4️⃣ Print the sum of first 10 natural numbers
let sum = 0;

for (let l = 1; l <= 10; l++) {
    sum = sum + l
}

console.log(sum);

// 5️⃣ Print the multiplication table of 5

let num = 5;

for (m = 1; m <= 10; m++) {
    console.log(`${num} * ${m} =${num * m}`);
}







